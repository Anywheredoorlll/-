"""Render a readable, clause-level TXT while retaining raw source locators.

This is a presentation artifact, not a replacement for frozen evidence quotes.
Tables and missing Latin spaces are recovered from PDF geometry, never inferred
from flattened text or generated by a model.
"""
from __future__ import annotations

import re
from contextlib import ExitStack

import pymupdf as fitz

from aviation_ft import core

VERSION = "clause-txt-v2"
CLAUSE = re.compile(r"^(\d+(?:\.\d+){2,})\s*")
SECTION = re.compile(r"^(\d+(?:\.\d+)?)\s+(.+)$")
FIGURE = re.compile(r"^图\s*\d+(?:\.\d+)+")
WIDTH_MAP = {i: i - 0xFEE0 for i in range(0xFF01, 0xFF5F)}
WIDTH_MAP.update({ord(c): c for c in "，；：！？（）"})
WIDTH_MAP.update({0x3000: " ", ord(core.PDF_CLAUSE_DOT): ".",
                  ord(core.PDF_LEADER_DOT): "…", ord("ꎬ"): "，",
                  ord("ꎮ"): "。", ord("ꎻ"): "；", ord("«"): "《", ord("»"): "》"})


def normalize(text: str) -> str:
    # Unlike NFKC, width folding does not turn ² into 2 or ℃ into °C.
    text = text.translate(WIDTH_MAP)
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"(?<=[\u4e00-\u9fff，。；、：]) +(?=[\u4e00-\u9fff])", "", text)
    text = re.sub(r" +([，。；、：])", r"\1", text)
    text = re.sub(r"([（(《]) +", r"\1", text)
    text = re.sub(r" +([）)》])", r"\1", text)
    return text.strip()


def geometry_text_repairs(pdf_page) -> dict[str, str]:
    repairs = {}
    for block in pdf_page.get_text("rawdict")["blocks"]:
        for line in block.get("lines", []):
            previous_text = ""
            for span in line["spans"]:
                chars = span["chars"]
                original = "".join(c["c"] for c in chars)
                if (span.get("flags", 0) & 1 and previous_text.endswith(("m", "ｍ"))
                        and normalize(original) in {"2", "3"}):
                    repairs[previous_text[-1] + original] = previous_text[-1] + {"2": "²", "3": "³"}[normalize(original)]
                previous_text = original
                if not re.fullmatch(r"[Ａ-Ｚａ-ｚA-Za-z]+", original):
                    continue
                result = ""
                for i, char in enumerate(chars):
                    if i and char["bbox"][0] - chars[i - 1]["bbox"][2] > span["size"] * 0.20:
                        result += " "
                    result += char["c"]
                if result != original:
                    repairs[original] = result
    return repairs


def table_matrix(table, repairs=None) -> tuple[list[list[str]], int]:
    """Fill only geometrically spanned cells; real blank cells remain blank."""
    rows = table.extract()
    cells = [(tuple(box), rows[r][c]) for r, row in enumerate(table.rows)
             for c, box in enumerate(row.cells) if box is not None]
    xs = sorted({round(box[i], 2) for box, _ in cells for i in (0, 2)})
    ys = sorted({round(box[i], 2) for box, _ in cells for i in (1, 3)})
    if len(xs) != table.col_count + 1 or len(ys) != table.row_count + 1:
        raise ValueError("单元格边界与表格行列数不一致")
    output = []
    for r, row in enumerate(rows):
        values = []
        for c, value in enumerate(row):
            if value is None:
                x, y = (xs[c] + xs[c + 1]) / 2, (ys[r] + ys[r + 1]) / 2
                covering = [v for box, v in cells if box[0] <= x <= box[2] and box[1] <= y <= box[3]]
                if len(covering) != 1:
                    raise ValueError("无法确定合并单元格的覆盖范围")
                value = covering[0]
            value = value or ""
            for original, fixed in (repairs or {}).items():
                value = value.replace(original, fixed)
            values.append(normalize(core._prose_text([{"text": value}])))
        output.append(values)
    # A vertically merged header plus a nonnumeric second row denotes two tiers.
    header_rows = 1
    if len(rows) > 1 and any(box and box[3] > ys[1] + 1 for box in table.rows[0].cells):
        if all(not re.match(r"^[\dＡ-ＺA-Z]", value or "") for value in rows[1]):
            header_rows = 2
    if header_rows == 2:
        header = [" / ".join(dict.fromkeys([output[0][c], output[1][c]])) for c in range(table.col_count)]
        output = [header] + output[2:]
    return output, header_rows


class PdfLayout:
    def __init__(self, pdf):
        self.pdf = pdf
        self.repairs = {}
        self.tables = {}

    def text(self, unit):
        text = unit["text"]
        if self.pdf:
            for n in range(unit["pdf_page"], unit["end_pdf_page"] + 1):
                if n not in self.repairs:
                    self.repairs[n] = geometry_text_repairs(self.pdf[n - 1])
                for original, fixed in sorted(self.repairs[n].items(), key=lambda pair: -len(pair[0])):
                    text = text.replace(original, fixed)
        text = normalize(text)
        # Terms occupy a distinct first physical line in this layout. Keep
        # the term, its English label, and its definition visually separate.
        first_line = unit["raw_text"].splitlines()[0]
        for repairs in self.repairs.values():
            for original, fixed in sorted(repairs.items(), key=lambda pair: -len(pair[0])):
                first_line = first_line.replace(original, fixed)
        first_line = normalize(first_line)
        term = re.fullmatch(r"(\d+(?:\.\d+){2,}\s+[\u4e00-\u9fff]+)([A-Za-z][A-Za-z -]+)", first_line)
        if term and text.startswith(first_line):
            text = term[1] + "\n英文术语：" + term[2] + "\n" + text[len(first_line):].lstrip()
        # Reference lists are often emitted as a single block by the PDF.
        if len(re.findall(r"\[\d+\]", text)) >= 2:
            text = re.sub(r"(?<!\n)(\[\d+\])", r"\n\1", text)
        return text

    def render_table(self, unit):
        if not self.pdf:
            return self.text(unit), [], ["缺少原始 PDF，未恢复表格行列"]
        title = normalize(unit["text"].splitlines()[0])
        grids, locations, warnings = [], [], []
        for n in range(unit["pdf_page"], unit["end_pdf_page"] + 1):
            if n not in self.tables:
                # Store plain data while the page/table object is still alive.
                page = self.pdf[n - 1]
                self.tables[n] = []
                for table in page.find_tables().tables:
                    try:
                        if n not in self.repairs:
                            self.repairs[n] = geometry_text_repairs(page)
                        matrix, header_rows = table_matrix(table, self.repairs[n])
                        self.tables[n].append((list(table.bbox), matrix, header_rows, None))
                    except ValueError as exc:
                        self.tables[n].append((list(table.bbox), [], 0, str(exc)))
            boxes = [loc["bbox"] for loc in unit["source_locations"] if loc["pdf_page"] == n]
            for box, matrix, header_rows, error in self.tables[n]:
                # A table must overlap the source unit, not just share its page.
                rect = fitz.Rect(box)
                if not any(rect.contains(fitz.Point((b[0]+b[2])/2, (b[1]+b[3])/2)) for b in boxes):
                    continue
                if error:
                    warnings.append(f"PDF 第 {n} 页：{error}")
                    continue
                grids.append(matrix)
                locations.append({"pdf_page": n, "bbox": box, "rows": matrix, "header_rows": header_rows})
        if not grids or warnings:
            return "[表格行列未能可靠恢复，请核对原 PDF]\n" + self.text(unit), locations, warnings or ["未检出可靠表格边界"]
        rows = list(grids[0])
        for matrix in grids[1:]:
            if matrix[0] != rows[0]:
                return "[续表表头不一致，请核对原 PDF]\n" + self.text(unit), locations, ["续表表头不一致"]
            rows.extend(matrix[1:])
        # Explicit separators preserve blank checkbox columns in plain text.
        lines = [title, " | ".join(rows[0]), " | ".join("---" for _ in rows[0])]
        lines.extend(" | ".join(row) for row in rows[1:])
        return "\n".join(lines), locations, []


def document_blocks(units, layout):
    # Skip cover/foreword/TOC only when a real numbered body is found.
    start_page = next((u["pdf_page"] for u in units
                       if CLAUSE.match(normalize(u["text"]))
                       and core.PDF_LEADER_DOT not in u["text"]), None)
    excluded = [u for u in units if start_page is not None and u["pdf_page"] < start_page]
    units = [u for u in units if start_page is None or u["pdf_page"] >= start_page]
    events, current, section = [], None, []

    def flush():
        nonlocal current
        if current:
            events.append(current)
            current = None

    for u in units:
        text = layout.text(u)
        heading = u["kind"] == "heading" or text in {"标准用词说明", "引用标准名录"}
        if heading:
            flush()
            # A chapter title may be split into separate visual lines.
            text = re.sub(r"^(\d+)\s*(?=[\u4e00-\u9fff])", r"\1 ", text)
            match = SECTION.match(text)
            depth = match[1].count(".") if match else 0
            section = (section[:depth] + [text]) if match else [text]
            events.append({"heading": text, "source_locations": u["source_locations"]})
            continue
        clause = CLAUSE.match(text)
        # Do not group across missing PDF pages or unrelated unnumbered paragraphs.
        if clause or (current and (u["pdf_page"] > current["end_pdf_page"] + 1
                                  or (u.get("parse_version") == "parse-v2"
                                      and u["pdf_page"] > current["end_pdf_page"]))):
            flush()
        if current and not section and not current["clause"]:
            flush()
        if current is None:
            current = {"doc_id": u["doc_id"], "clause": clause[1] if clause else "",
                       "section": list(section), "pdf_page": u["pdf_page"],
                       "end_pdf_page": u["end_pdf_page"], "parts": [],
                       "source_locations": [], "source_fragments": [],
                       "source_semantic_ids": [], "raw_source_parts": [],
                       "tables": [], "warnings": []}
        if u["kind"] == "table":
            text, tables, warnings = layout.render_table(u)
            current["tables"].extend(tables)
            current["warnings"].extend(warnings)
        elif FIGURE.match(text):
            text += f"\n[图形请见原 PDF 第 {u['pdf_page']} 页]"
        if u["kind"] == "list_item" and not clause:
            text = re.sub(r"^(\d+)\s+", r"\1. ", text)
            if re.match(r"^\d+[)）]", text):
                text = "  " + text
        # Keep explanations, list items and captions on their own lines.
        current["parts"].append(text)
        current["source_locations"].extend(u["source_locations"])
        offset = len(current["source_fragments"])
        current["source_fragments"].extend(
            {**fragment, "order": offset + position}
            for position, fragment in enumerate(u.get("source_fragments", [])))
        current["source_semantic_ids"].append(u["semantic_id"])
        current["raw_source_parts"].append(u["raw_text"])
        if (u.get("cross_page_merge") or {}).get("decision") == "proposed":
            current["warnings"].append("跨页合并仅为未确认建议，整理版保持分开")
        current["end_pdf_page"] = max(current["end_pdf_page"], u["end_pdf_page"])
    flush()
    return events, excluded


def build(job_id):
    root = core.job_dir(job_id)
    pages = core.pages_for(job_id)
    if not pages:
        raise ValueError("请先解析 PDF，再生成整体 TXT")
    meta = core.load_job(job_id)
    quality_issues = core.read_jsonl(root / "parsed/issues.jsonl")
    parse_version = sorted({page.get("parse_version", "legacy") for page in pages})
    sections, records, exclusions, warnings = [], [], [], []
    merged_cross_page = 0
    with ExitStack() as stack:
        for doc in meta["documents"]:
            path = root / "raw_pdf" / doc["filename"]
            pdf = None
            if path.is_file():
                if doc.get("sha256") and core.sha256_file(path) != doc["sha256"]:
                    raise ValueError("原始 PDF 哈希不匹配，不能生成整理版 TXT")
                pdf = stack.enter_context(fitz.open(path))
            document_pages = []
            for page in pages:
                if page["doc_id"] != doc["doc_id"]:
                    continue
                # A short publication-imprint page is back matter, not a
                # continuation of the reference list on the preceding page.
                body = "\n".join(b["text"] for b in page["blocks"])
                imprint = re.search(r"(?:成本价|定价|统一书号|ISBN)[:：\s]", body)
                if imprint and len(body) < 250 and page["pdf_page"] >= max(p["pdf_page"] for p in pages if p["doc_id"] == doc["doc_id"]) - 1:
                    exclusions.append({"doc_id": doc["doc_id"], "pdf_page": page["pdf_page"],
                                       "block_ids": [b["block_id"] for b in page["blocks"]],
                                       "reason": "封底出版信息"})
                    continue
                document_pages.append(page)
            units = core.semantic_blocks_for_document(document_pages, core.confirmed_merge_pairs(job_id))
            merged_cross_page += sum(len({loc["pdf_page"] for loc in u["source_locations"]}) - 1 for u in units)
            events, excluded = document_blocks(units, PdfLayout(pdf))
            exclusions.extend({"doc_id": doc["doc_id"], "pdf_page": u["pdf_page"], "semantic_id": u["semantic_id"],
                               "reason": "正文起始页之前的封面、前言或目录"} for u in excluded)
            lines = [f"# 文档：{doc['filename']}"]
            index = 0
            for event in events:
                if "heading" in event:
                    lines.append("# " + event["heading"])
                    continue
                index += 1
                label = str(event["pdf_page"])
                if event["end_pdf_page"] != event["pdf_page"]:
                    label += f"-{event['end_pdf_page']}"
                rendered_parts = event.pop("parts")
                raw_parts = event.pop("raw_source_parts")
                text = "\n\n".join(rendered_parts)
                raw_text = "\n".join(raw_parts)
                transform_map, raw_offset, text_offset = [], 0, 0
                for semantic_id, raw_part, rendered_part in zip(event["source_semantic_ids"], raw_parts, rendered_parts):
                    transform_map.append({"semantic_id": semantic_id,
                        "raw_start": raw_offset, "raw_end": raw_offset + len(raw_part),
                        "rendered_start": text_offset, "rendered_end": text_offset + len(rendered_part),
                        "status": "unchanged" if raw_part == rendered_part else "transformed"})
                    raw_offset += len(raw_part) + 1
                    text_offset += len(rendered_part) + 2
                event.update({"text": text, "raw_source_text": raw_text,
                              "transform_map": transform_map,
                              "parse_version": parse_version, "source_pdf_sha256": doc.get("sha256"),
                              "export_id": f"{doc['doc_id']}-txt-{index:04d}"})
                records.append(event)
                warnings.extend(event["warnings"])
                context = "章节：" + " > ".join(event["section"]) + "\n" if event["section"] else ""
                lines.append(f"## 证据块 {index:04d} | PDF 页 {label}\n{context}{text}")
            sections.append("\n\n".join(lines))
    notice = ["# 整理版 TXT（未经逐页人工验收）", "解析版本：" + ", ".join(parse_version),
              f"待核实提取问题：{sum(x.get('status') == '待处理' for x in quality_issues)} 项。",
              "字符范围以对应解析候选原文的 Python Unicode 左闭右开索引为准；整理文字不可替代 PDF 原文。"]
    if exclusions:
        notice.append(f"整理展示排除 {len(exclusions)} 项；详情见 parsed/txt_report.json，原始解析页和 PDF 保留。")
    for issue in quality_issues:
        notice.append(f"提取告警：{issue['doc_id']} PDF 第 {issue['pdf_page']} 页 | "
                      f"{issue['code']} | {issue['severity']} | {issue['status']} | {issue['message'][:160]}")
    for exclusion in exclusions:
        notice.append(f"展示排除：{exclusion['doc_id']} PDF 第 {exclusion.get('pdf_page', '?')} 页 | {exclusion['reason']}")
    content = "\n".join(notice) + "\n\n" + "\n\n".join(sections).strip() + "\n"
    # Unknown private glyphs remain visible and are reported, never silently dropped.
    unknown = sorted({c for c in content if 0xE000 <= ord(c) <= 0xF8FF or 0xF0000 <= ord(c) <= 0x10FFFD})
    if unknown:
        warnings.append("存在未映射的 PDF 字符：" + ", ".join(f"U+{ord(c):04X}" for c in unknown))
    report = {"filename": "semantic_corpus.txt", "format_version": VERSION,
              "parse_versions": parse_version,
              "quality_issues": len(quality_issues),
              "pending_quality_issues": sum(x.get("status") == "待处理" for x in quality_issues),
              "documents": len(meta["documents"]), "pages": len(pages),
              "semantic_units": len(records), "merged_cross_page": merged_cross_page,
              "chars": len(content), "excluded_frontmatter_units": sum("semantic_id" in e for e in exclusions),
              "excluded_imprint_pages": sum(e["reason"] == "封底出版信息" for e in exclusions),
              "reconstructed_table_fragments": sum(len(r["tables"]) for r in records),
              "warnings": warnings}
    return content, records, exclusions, report
